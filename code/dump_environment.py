# -*- coding: utf-8 -*-
"""Write the environment file the fifth review asked for.

    python dump_environment.py            # writes requirements.txt
    python dump_environment.py --print    # only prints

The public experiments need the core packages; the private corpus and the
non-parametric baselines are optional and marked as such.  The Hugging Face
revision of the sentence encoder is recorded too (the code runs offline, so a
fresh environment needs to fetch that exact commit).
"""

from __future__ import annotations

import importlib
import sys
from pathlib import Path

CORE = ["numpy", "scipy", "pandas", "scikit-learn", "gensim", "torch",
        "transformers", "sentence-transformers", "matplotlib"]
OPTIONAL = ["bertopic", "top2vec", "contextualized-topic-models", "jieba",
            "pyarrow"]

# distribution name -> import name, where they differ
IMPORT_NAMES = {"scikit-learn": "sklearn",
                "sentence-transformers": "sentence_transformers",
                "contextualized-topic-models": "contextualized_topic_models"}


def version_of(module: str) -> str | None:
    try:
        mod = importlib.import_module(IMPORT_NAMES.get(module, module))
    except Exception:  # noqa: BLE001
        return None
    return getattr(mod, "__version__", None)


def cached_revision(cache_name: str) -> str | None:
    """Commit hash recorded in the local Hugging Face cache for a model."""
    ref = (Path.home() / ".cache" / "huggingface" / "hub" / cache_name
           / "refs" / "main")
    if ref.exists():
        return ref.read_text(encoding="utf-8").strip() or None
    return None


def main() -> int:
    lines = [f"# python {sys.version.split()[0]}",
             "# generated by dump_environment.py"]
    missing = []
    for group, names in (("core", CORE), ("optional", OPTIONAL)):
        lines.append("")
        lines.append(f"# {group}")
        for name in names:
            version = version_of(name)
            if version is None:
                missing.append(name)
                lines.append(f"# {name}  (not installed here)")
            else:
                lines.append(f"{name}=={version}")
    # the encoder revision is what the archived runs actually used; read it
    # from the local Hugging Face cache instead of hitting the network
    revision = cached_revision(
        "models--sentence-transformers--all-MiniLM-L6-v2")
    lines.append("")
    lines.append("# sentence encoder weights "
                 "(see config.EMBEDDING_MODEL_NAME)")
    if revision:
        lines.append(f"# model  sentence-transformers/all-MiniLM-L6-v2"
                     f"@{revision}")
        lines.append(f"#   -> pass revision=\"{revision}\" when loading it")
    else:
        lines.append("# revision not found in the local HF cache")
    text = "\n".join(lines) + "\n"
    if "--print" in sys.argv:
        print(text)
    else:
        (Path(__file__).resolve().parent / "requirements.txt").write_text(
            text, encoding="utf-8")
        print("wrote requirements.txt")
    if missing:
        print("not installed in this environment:", ", ".join(missing))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
